    /// <summary>字 → 区分の CSS クラス（<c>kg-1</c>〜<c>kg-6</c>＝習う学年、<c>kg-j</c>＝中学以降の常用漢字）。</summary>
    private static readonly Dictionary<string, string> ClassByChar = BuildMap();

    private static Dictionary<string, string> BuildMap()
    {
        var map = new Dictionary<string, string>(StringComparer.Ordinal);
        void Add(string chars, string cls)
        {
            foreach (char c in chars) map[c.ToString()] = cls;
        }
        Add(Grade1, "kg-1");
        Add(Grade2, "kg-2");
        Add(Grade3, "kg-3");
        Add(Grade4, "kg-4");
        Add(Grade5, "kg-5");
        Add(Grade6, "kg-6");
        Add(JoyoAfterElementary, "kg-j");
        return map;
    }

